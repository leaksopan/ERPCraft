//! `bc-parity inventory`: every page and report of BC's W1 Base Application and of the W1 apps,
//! grouped by area, each marked done when ERPCraft has it. The full to-do list behind
//! docs/roadmap.md.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use erpcraft_engine::meta::Metadata;

/// BC reports ERPCraft produces (as commands or prints), by BC report name.
const REPORTS_DONE: &[&str] = &[
    "Trial Balance",
    "Aged Accounts Receivable",
    "Aged Accounts Payable",
    "Inventory Valuation",
    "Fixed Asset - Book Value 01",
    "Standard Sales - Quote",
    "Standard Sales - Order Conf.",
    "Standard Sales - Invoice",
    "Standard Sales - Credit Memo",
    "Standard Sales - Pro Forma Inv",
    "Sales - Shipment",
    "Standard Purchase - Order",
    "Purchase - Invoice",
    "Purchase - Credit Memo",
    "Purchase - Receipt",
    "Work Order",
];

struct Object {
    kind: &'static str,
    id: u32,
    name: String,
    page_type: String,
}

/// `page 21 "Customer Card"` and the PageType, read from the first lines of the file.
fn read_object(path: &Path, keyword: &'static str) -> Option<Object> {
    let text = std::fs::read_to_string(path).ok()?;
    let prefix = format!("{keyword} ");
    let line = text.lines().find(|l| l.starts_with(&prefix))?;
    let mut words = line[prefix.len()..].split_whitespace();
    let id: u32 = words.next()?.parse().ok()?;
    let name = words.collect::<Vec<_>>().join(" ").trim_matches('"').to_string();
    let page_type = text
        .lines()
        .take(80)
        .find_map(|l| l.trim().strip_prefix("PageType = ").map(|v| v.trim_end_matches(';').to_string()))
        .unwrap_or_else(|| if keyword == "page" { "Card".to_string() } else { String::new() });
    Some(Object { kind: if keyword == "page" { "page" } else { "report" }, id, name, page_type })
}

fn walk(root: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(root) else { return };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk(&p, out);
        } else if p.to_string_lossy().ends_with(".Page.al") || p.to_string_lossy().ends_with(".Report.al") {
            out.push(p);
        }
    }
}

/// Objects under `root`, grouped by their first one or two folders.
fn collect(root: &Path, depth: usize) -> BTreeMap<String, BTreeMap<String, Vec<Object>>> {
    let mut files = Vec::new();
    walk(root, &mut files);
    let mut out: BTreeMap<String, BTreeMap<String, Vec<Object>>> = BTreeMap::new();
    for f in files {
        let keyword = if f.to_string_lossy().ends_with(".Page.al") { "page" } else { "report" };
        let Some(o) = read_object(&f, keyword) else { continue };
        let rel = f.strip_prefix(root).unwrap_or(&f);
        let parts: Vec<String> = rel.parent().map(|p| p.components().map(|c| c.as_os_str().to_string_lossy().to_string()).collect()).unwrap_or_default();
        let area = parts.first().cloned().unwrap_or_else(|| "(root)".to_string());
        let sub = if depth > 1 { parts.get(1).cloned().unwrap_or_else(|| "(general)".to_string()) } else { String::new() };
        out.entry(area).or_default().entry(sub).or_default().push(o);
    }
    for subs in out.values_mut() {
        for list in subs.values_mut() {
            list.sort_by(|a, b| (a.kind, a.id).cmp(&(b.kind, b.id)));
        }
    }
    out
}

fn done(o: &Object, pages: &BTreeSet<u32>) -> bool {
    match o.kind {
        "page" => pages.contains(&o.id),
        _ => REPORTS_DONE.contains(&o.name.as_str()),
    }
}

fn count(list: &[&Object], pages: &BTreeSet<u32>, kind: &str) -> (usize, usize) {
    let of_kind: Vec<&&Object> = list.iter().filter(|o| o.kind == kind).collect();
    (of_kind.iter().filter(|o| done(o, pages)).count(), of_kind.len())
}

fn line(o: &Object, pages: &BTreeSet<u32>) -> String {
    let mark = if done(o, pages) { "x" } else { " " };
    let ty = if o.kind == "page" { o.page_type.clone() } else { "Report".to_string() };
    format!("- [{mark}] {} {} {} ({ty})", if o.kind == "page" { "Page" } else { "Report" }, o.id, o.name)
}

pub fn generate(meta: &Metadata, base_app: &Path, apps: &Path) -> String {
    let pages: BTreeSet<u32> = meta.pages.values().map(|p| p.object_id).filter(|id| *id > 0 && *id < 50000).collect();
    let base = collect(base_app, 2);
    let mut out = String::from(
        "# Business Central feature inventory\n\n\
         Generated by `cargo run -p bc-parity -- inventory` from BCApps W1. Do not edit by hand: run it again.\n\n\
         Every page and report of the W1 Base Application and of the W1 apps, per area. A page is ticked when\n\
         ERPCraft has the page (same object id); a report when ERPCraft produces it. A ticked page can still have\n\
         gaps in fields or actions: `cargo run -p bc-parity -- --page <id>` lists them. [docs/roadmap.md](roadmap.md)\n\
         orders this list into phases.\n\n",
    );
    // Summary.
    let mut total = [(0usize, 0usize), (0, 0)];
    let mut summary = String::from("| Area | Pages done | Pages | Reports done | Reports |\n| --- | ---: | ---: | ---: | ---: |\n");
    for (area, subs) in &base {
        let all: Vec<&Object> = subs.values().flatten().collect();
        let (pd, pt) = count(&all, &pages, "page");
        let (rd, rt) = count(&all, &pages, "report");
        if pt + rt == 0 {
            continue;
        }
        total[0].0 += pd;
        total[0].1 += pt;
        total[1].0 += rd;
        total[1].1 += rt;
        let _ = writeln!(summary, "| {area} | {pd} | {pt} | {rd} | {rt} |");
    }
    let _ = writeln!(summary, "| **Base Application** | **{}** | **{}** | **{}** | **{}** |", total[0].0, total[0].1, total[1].0, total[1].1);
    let _ = writeln!(out, "## Base Application\n\n{summary}");
    for (area, subs) in &base {
        let all: Vec<&Object> = subs.values().flatten().collect();
        if all.is_empty() {
            continue;
        }
        let (pd, pt) = count(&all, &pages, "page");
        let (rd, rt) = count(&all, &pages, "report");
        let _ = writeln!(out, "### {area}\n\nPages {pd} / {pt}, reports {rd} / {rt}.\n");
        for (sub, list) in subs {
            let refs: Vec<&Object> = list.iter().collect();
            let (spd, spt) = count(&refs, &pages, "page");
            let (srd, srt) = count(&refs, &pages, "report");
            let _ = writeln!(out, "<details><summary>{area} / {sub}: pages {spd} / {spt}, reports {srd} / {srt}</summary>\n");
            for o in list {
                let _ = writeln!(out, "{}", line(o, &pages));
            }
            let _ = writeln!(out, "\n</details>\n");
        }
    }
    // W1 apps: one section each.
    let mut app_dirs: Vec<PathBuf> = std::fs::read_dir(apps).map(|r| r.flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect()).unwrap_or_default();
    app_dirs.sort();
    let mut apps_summary = String::from("| App | Pages | Reports |\n| --- | ---: | ---: |\n");
    let mut apps_detail = String::new();
    for dir in app_dirs {
        let name = dir.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
        let app_root = if dir.join("App").is_dir() { dir.join("App") } else if dir.join("app").is_dir() { dir.join("app") } else { dir.clone() };
        let grouped = collect(&app_root, 1);
        let all: Vec<&Object> = grouped.values().flat_map(|s| s.values().flatten()).collect();
        if all.is_empty() {
            continue;
        }
        let (pd, pt) = count(&all, &pages, "page");
        let (rd, rt) = count(&all, &pages, "report");
        let _ = writeln!(apps_summary, "| {name} | {pd} / {pt} | {rd} / {rt} |");
        let _ = writeln!(apps_detail, "<details><summary>{name}: pages {pd} / {pt}, reports {rd} / {rt}</summary>\n");
        let mut sorted: Vec<&Object> = all;
        sorted.sort_by(|a, b| (a.kind, a.id).cmp(&(b.kind, b.id)));
        for o in sorted {
            let _ = writeln!(apps_detail, "{}", line(o, &pages));
        }
        let _ = writeln!(apps_detail, "\n</details>\n");
    }
    let _ = writeln!(out, "## W1 apps\n\nApps Microsoft ships beside the Base Application (Shopify, E-Documents, Subscription Billing, Sustainability, …).\n\n{apps_summary}\n{apps_detail}");
    out
}

/// Reports the generator ticks that no longer exist under that name in BCApps.
pub fn unknown_reports(base_app: &Path) -> Vec<&'static str> {
    let base = collect(base_app, 1);
    let names: BTreeSet<String> = base.values().flat_map(|s| s.values().flatten()).filter(|o| o.kind == "report").map(|o| o.name.clone()).collect();
    REPORTS_DONE.iter().copied().filter(|r| !names.contains(*r)).collect()
}
